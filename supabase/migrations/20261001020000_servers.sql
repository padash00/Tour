-- F16 Arena — этап 3: Server Agent, инстансы CS2, события MatchZy, статистика по картам.

-- id матча для MatchZy (MatchZy принимает только целое число)
alter table matches add column matchzy_id bigint generated by default as identity unique;
alter table matches add column server_instance text;
alter table matches add column server_state text check (server_state in ('assigned', 'loading', 'ready', 'error'));

-- ───────────────────────── хост и инстансы (заполняет агент)
create table server_host (
  id           text primary key default 'main',
  lan_ip       text,
  last_seen_at timestamptz,
  info         jsonb not null default '{}'::jsonb   -- cpu, ram, disk, build, версии плагинов
);

create table server_instances (
  name             text primary key,                 -- CS2-01
  port             int  not null,
  role             text not null default 'active' check (role in ('active', 'reserve')),
  running          boolean not null default false,
  gamestate        text,                              -- из get5_status: none / warmup / knife / live / post_game …
  map              text,
  players          int,
  matchzy_match_id bigint,
  match_id         uuid references matches(id) on delete set null,
  last_seen_at     timestamptz,
  info             jsonb not null default '{}'::jsonb
);

insert into server_instances (name, port, role) values
  ('CS2-01', 27015, 'active'),
  ('CS2-02', 27115, 'active'),
  ('CS2-03', 27215, 'active'),
