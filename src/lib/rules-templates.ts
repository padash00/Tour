/**
 * Шаблоны регламента и требований для турниров F16 Arena (1×1, 2×2 Wingman, 5×5).
 * Чистые функции без обращения к базе — используются в форме турнира в админке.
 * Цифры (BO, раунды, паузы, нож, овертайм) берутся из текущих настроек формы.
 */

export type RulesOptions = {
  /** размер состава: 1 — дуэль, 2 — Wingman, 5 — классика */
  size: 1 | 2 | 5;
  bracket: string;
  bo: number;
  finalBo: number;
  knife: boolean;
  overtime: boolean;
  timeouts: number;
  timeoutSec: number;
  techPauses: number;
  techSec: number;
  isLan: boolean;
  /** в маппуле одна карта — вето нет */
  singleMap: boolean;
  prizePool?: string;
};

const plural = (n: number, one: string, few: string, many: string) => {
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return one;
  if (m10 >= 2 && m10 <= 4 && (m100 < 10 || m100 >= 20)) return few;
  return many;
};

const BRACKET: Record<string, string> = {
  single_elimination: "Single Elimination — одно поражение, и команда выбывает",
  double_elimination: "Double Elimination — команда выбывает после двух поражений (верхняя и нижняя сетка)",
  round_robin: "круговая система — каждый играет с каждым, места по таблице",
  groups_playoff: "групповой этап по круговой системе, затем плей-офф",
  swiss: "швейцарская система — соперники подбираются по одинаковому счёту",
  swiss_playoff: "швейцарская система, затем плей-офф",
};

export function rulesTemplate(o: RulesOptions): string {
  const who = o.size === 1 ? "игрок" : "команда";
  const whoGen = o.size === 1 ? "игрока" : "команды";
  const whoPl = o.size === 1 ? "игроки" : "команды";
  const rounds = o.size === 2 ? 16 : 24;
  const half = rounds / 2;
  const otAt = `${half}:${half}`;
  const ready = o.size * 2;
  const sections: string[] = [];

  sections.push(
    `1. ФОРМАТ
1.1. Сетка: ${BRACKET[o.bracket] ?? o.bracket}.
1.2. Матчи — BO${o.bo}${o.finalBo !== o.bo ? `, финальная стадия — BO${o.finalBo}` : ""}.${
      o.bracket === "double_elimination" ? " Гранд-финал — BO5, команда из верхней сетки начинает со счётом 1:0 по картам." : ""
    }
1.3. ${o.size === 1 ? "Дуэль 1×1" : o.size === 2 ? "Wingman 2×2" : "Классика 5×5"}: до ${half + 1} побед в раундах (MR${rounds}).
1.4. Серия завершается досрочно, когда одна из сторон набрала нужное число карт.`,
  );

  sections.push(
    o.singleMap
      ? `2. КАРТЫ
2.1. Все матчи играются на одной карте турнира — вето не проводится.`
      : `2. ВЕТО
2.1. Вето проходит на странице матча до выдачи сервера. Первым ходит ${who} с более высоким посевом.
2.2. BO1: баны по очереди до одной карты. BO3: бан, бан, пик, пик, бан, бан, оставшаяся — решающая. BO5: бан, бан, далее пики, последняя — решающая.
2.3. На каждый ход — 60 секунд. Если время вышло, карта выбирается случайно; оспорить такой выбор нельзя.
2.4. Вето ${o.size === 1 ? "делает сам игрок" : "делает капитан команды"}.`,
  );

  sections.push(
    `3. СТОРОНЫ
3.1. ${
      o.knife
        ? "Стороны определяет ножевой раунд. Победитель пишет в чат .stay (остаться) или .switch (сменить сторону)."
        : `Стороны фиксированы: ${o.size === 1 ? "первый игрок в паре" : "команда 1"} начинает за CT, на следующей карте серии — наоборот.`
    }`,
  );

  sections.push(
    `4. ОВЕРТАЙМ
4.1. ${
      o.overtime
        ? `При счёте ${otAt} играется овертайм MR3 (до 4 побед из 6 раундов), при новой ничьей — следующий овертайм.`
        : `Овертайм не играется: при счёте ${otAt} карта заканчивается ничьей и решается по решению администратора.`
    }`,
  );

  sections.push(
    `5. ПАУЗЫ
${
  o.size === 1
    ? ""
    : `5.1. Тактические паузы: ${o.timeouts} ${plural(o.timeouts, "пауза", "паузы", "пауз")} по ${o.timeoutSec} секунд на команду за карту (.tac).\n`
}${o.size === 1 ? "5.1" : "5.2"}. Технические паузы: ${o.techPauses} ${plural(o.techPauses, "пауза", "паузы", "пауз")} до ${Math.round(o.techSec / 60)} минут на ${whoGen.replace("команды", "команду").replace("игрока", "игрока")} за карту (.tech) — только при реальной технической проблеме (отвал, зависание, железо).
${o.size === 1 ? "5.2" : "5.3"}. Снятие паузы — .unpause обеими сторонами. Злоупотребление паузами — предупреждение, затем техническое поражение на карте.`,
  );

  sections.push(
    `6. ОПОЗДАНИЕ И НЕЯВКА
6.1. После выдачи адреса сервера на подключение отводится 15 минут.
6.2. Матч стартует, когда на сервере готовы все ${ready} ${plural(ready, "игрок", "игрока", "игроков")} (.ready / .r в разминке).
6.3. Если ${o.size === 1 ? "игрок не явился или не готов" : "команда не явилась или не готова"} вовремя — решение принимает администратор турнира: перенос, ожидание или техническое поражение.`,
  );

  if (o.size > 1) {
    sections.push(
      `7. СОСТАВ И ЗАМЕНЫ
7.1. Играют только заявленные на турнир игроки — сервер пускает по SteamID.
7.2. Замена основного игрока на заявленного запасного — только через администратора и только между картами.
7.3. Один игрок может выступать только за одну команду в рамках турнира.`,
    );
  }

  const n = o.size > 1 ? 8 : 7;
  sections.push(
    `${n}. ТЕХНИЧЕСКИЕ ПРОБЛЕМЫ
${n}.1. При падении сервера или массовом отвале администратор восстанавливает последний сыгранный раунд из бэкапа${
      o.singleMap ? " (если карта это поддерживает)" : ""
    } или переигрывает раунд.
${n}.2. Проблемы с собственным ПК, гарнитурой и настройками — ответственность ${o.isLan ? "игрока; на LAN администратор поможет заменить место или периферию" : "игрока"}.`,
  );

  sections.push(
    `${n + 1}. ЧЕСТНАЯ ИГРА
${n + 1}.1. Запрещены читы, макросы, скрипты, сторонние оверлеи, эксплойты карты и любое ПО, дающее преимущество.
${n + 1}.2. ${
      o.isLan
        ? "Турнир проходит на LAN: администраторы вправе проверить ПК и периферию игрока в любой момент."
        : "Администраторы вправе запросить демо и проверку ПК."
    }
${n + 1}.3. Нарушение — дисквалификация ${whoGen} без возврата взноса.`,
  );

  sections.push(
    `${n + 2}. ПОВЕДЕНИЕ
${n + 2}.1. Уважение к соперникам, судьям и зрителям. Оскорбления, токсичность и намеренный срыв матча — предупреждение или дисквалификация.
${n + 2}.2. Решения администратора турнира окончательны.`,
  );

  sections.push(
    `${n + 3}. СПОРЫ
${n + 3}.1. Спор открывается на странице матча кнопкой «Спор» с описанием и доказательствами — не позднее 15 минут после окончания карты.
${n + 3}.2. До решения администратора результат матча может быть приостановлен.`,
  );

  sections.push(
    `${n + 4}. ПРИЗЫ
${n + 4}.1. ${o.prizePool && !/^\s*0+\s*$/.test(o.prizePool) ? `Призовой фонд: ${o.prizePool}. ` : ""}Призы выдаются ${whoPl === "команды" ? "капитану команды" : "игроку"} после завершения турнира и проверки результатов.`,
  );

  return sections.join("\n\n");
}

export function requirementsTemplate(o: Pick<RulesOptions, "size" | "isLan">): string {
  const lines = [
    "Аккаунт Steam, вход на платформу F16 Arena через Steam",
    o.size === 1
      ? "Дуэль 1×1: регистрация одной кнопкой, без команды"
      : `Состав: ${o.size === 2 ? "2 основных игрока и 1 запасной" : `${o.size} основных игроков и до 2 запасных`}, все на платформе`,
    "Один игрок — одна команда в рамках турнира",
    o.size === 1 ? "Check-in в отведённое время" : "Check-in капитаном в отведённое время",
    o.isLan ? "Явка в F16 Arena к началу check-in, своя периферия по желанию" : "Стабильный интернет и ПК, тянущий CS2",
  ];
  return lines.join("\n");
}
